export function matchAutomobileFaq(text: string, lang: AutomobileLang = "en-IN"): string | null {
  const lower = (text || "").toLowerCase();
  const kb = AUTOMOBILE_KB[lang] || AUTOMOBILE_KB["en-IN"];

  if (/\b(showroom|open|opening|close|closing|timings?|hours?|kab\s*khul|kitne\s*baje)\b/i.test(lower) && !/\b(service|workshop)\b/i.test(lower)) {
    return kb.showroomHours;
  }

  if (/\b(workshop|service\s*center|service\s*timing|service\s*hours)\b/i.test(lower)) {
    return kb.serviceCenterHours;
  }

  if (/\b(where|location|address|kahan|kidhar|showroom\s*address)\b/i.test(lower)) {
    return kb.locationDetails;
  }

  if (/\b(test\s*drive|home\s*test\s*drive|doorstep|driving\s*licen[sc]e)\b/i.test(lower) && /\b(policy|available|free|cost|charge|fees?|kaise)\b/i.test(lower)) {
    return kb.testDrivePolicy;
  }

  if (/\b(periodic|regular|maintenance|schedule|kitne\s*km|when\s*to\s*service)\b/i.test(lower)) {
    return kb.periodicServiceInfo;
  }

  if (/\b(warranty|guarantee|battery\s*warranty|shield)\b/i.test(lower)) {
    return kb.warrantyPolicy;
  }

  if (/\b(finance|loan|emi|interest|down\s*payment|kist|byaj)\b/i.test(lower)) {
    return kb.financeAndEmi;
  }

  if (/\b(insurance|policy|bima|renew|renewal|cashless|zero\s*dep)\b/i.test(lower)) {
    return kb.insuranceRenewal;
  }

  if (/\b(roadside|breakdown|towing|highway|troll\s*free|emergency\s*number)\b/i.test(lower)) {
    return kb.roadsideAssistanceContact;
  }

  return null;
}
